#!/usr/bin/env python3
"""Regenerate firmware assets from creative/creative.json (+ logo).

Edit creative/creative.json (and creative/logo.png), then:

  ./scripts/sync_creative.sh

Writes:
  lib/SomniumApp/Modes.h
  lib/SomniumApp/CreativeGen.h   (theme + font macro)
  lib/SomniumApp/LogoBitmap.h    (from creative/logo.png)
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CREATIVE_DIR = ROOT / "creative"
CREATIVE_JSON = CREATIVE_DIR / "creative.json"
APP = ROOT / "lib" / "SomniumApp"


def rgb565(rgb: list[int]) -> int:
    r, g, b = (int(rgb[0]), int(rgb[1]), int(rgb[2]))
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def validate_firmware_text(modes: list[dict], brand: dict) -> bool:
    firmware_text_fields = [
        ("brand.name", brand.get("name", "Somnium")),
        ("brand.tagline", brand.get("tagline", "")),
    ]
    for index, mode in enumerate(modes):
        for field in ("id", "label"):
            firmware_text_fields.append((f"modes[{index}].{field}", mode[field]))
    for field, value in firmware_text_fields:
        if not isinstance(value, str) or any(
            not 32 <= ord(character) <= 126 for character in value
        ):
            print(
                f"{field} must use printable ASCII for the firmware; "
                "replace special characters with plain text (for example, ... or -)",
                file=sys.stderr,
            )
            return False
    return True


def write_modes(modes: list[dict]) -> None:
    lines = [
        "#pragma once",
        "",
        "// GENERATED by tools/sync_creative.py — do not edit by hand.",
        "// Source: creative/creative.json",
        "",
        "#include <Arduino.h>",
        '#include "ModeBitmaps.h"',
        "",
        "namespace Somnium {",
        "namespace App {",
        "",
        "struct Mode {",
        "  const char *id;",
        "  const char *label;",
        "  uint16_t placeholderColor;",
        "  const uint16_t *preview;",
        "};",
        "",
        "constexpr Mode kModes[] = {",
    ]
    for index, m in enumerate(modes):
        tint = m.get("tint") or [80, 80, 90]
        cid = m["id"]
        label = m["label"]
        preview = f"kModePreview{index}" if m.get("preview") else "nullptr"
        lines.append(f'    {{"{cid}", "{label}", 0x{rgb565(tint):04X}, {preview}}},')
    lines += [
        "};",
        "constexpr int kModeCount = sizeof(kModes) / sizeof(kModes[0]);",
        "",
        "inline const Mode &modeAt(int index) {",
        "  int i = index % kModeCount;",
        "  if (i < 0) {",
        "    i += kModeCount;",
        "  }",
        "  return kModes[i];",
        "}",
        "",
        "}  // namespace App",
        "}  // namespace Somnium",
        "",
    ]
    path = APP / "Modes.h"
    path.write_text("\n".join(lines))
    print("wrote", path.relative_to(ROOT))


def write_mode_previews(modes: list[dict]) -> None:
    from PIL import Image, ImageOps

    width, height = 138, 82
    lines = [
        "#pragma once",
        "#include <Arduino.h>",
        f"constexpr int16_t kModePreviewWidth = {width};",
        f"constexpr int16_t kModePreviewHeight = {height};",
    ]
    for index, mode in enumerate(modes):
        if not mode.get("preview"):
            continue
        with Image.open(CREATIVE_DIR / mode["preview"]) as image:
            image = ImageOps.pad(
                ImageOps.exif_transpose(image).convert("RGB"),
                (width, height), method=Image.Resampling.LANCZOS, color=(0, 0, 0),
            )
            pixels = [
                f"0x{rgb565(image.getpixel((x, y))):04X}"
                for y in range(height) for x in range(width)
            ]
        lines.append(f"const uint16_t kModePreview{index}[{width * height}] PROGMEM = {{")
        for offset in range(0, len(pixels), 12):
            lines.append(",".join(pixels[offset:offset + 12]) + ",")
        lines.append("};")
    path = APP / "ModeBitmaps.h"
    path.write_text("\n".join(lines) + "\n")
    print("wrote", path.relative_to(ROOT))


def write_theme(theme: dict, ui: dict, brand: dict) -> None:
    font = ui.get("font", "FreeSerifBoldItalic12pt7b")
    name = brand.get("name", "Somnium")
    tag = brand.get("tagline", "")

    def c(key: str, default: list[int]) -> str:
        return f"0x{rgb565(theme.get(key, default)):04X}"

    lines = [
        "#pragma once",
        "",
        "// GENERATED by tools/sync_creative.py — do not edit by hand.",
        "// Source: creative/creative.json",
        "",
        f"#include <Fonts/{font}.h>",
        "",
        "namespace Somnium {",
        "namespace App {",
        "namespace Creative {",
        "",
        f'constexpr const char *kBrandName = "{name}";',
        f'constexpr const char *kBrandTagline = "{tag}";',
        f"#define SOMNIUM_TITLE_FONT {font}",
        "",
        f"constexpr uint16_t kColorBg = {c('bg', [0, 0, 0])};",
        f"constexpr uint16_t kColorSurface = {c('surface', [20, 12, 18])};",
        f"constexpr uint16_t kColorPanel = {c('panel', [36, 20, 30])};",
        f"constexpr uint16_t kColorPink = {c('pink', [255, 105, 180])};",
        f"constexpr uint16_t kColorPinkDim = {c('pinkDim', [200, 80, 140])};",
        f"constexpr uint16_t kColorMuted = {c('muted', [140, 110, 125])};",
        "",
        "}  // namespace Creative",
        "}  // namespace App",
        "}  // namespace Somnium",
        "",
    ]
    path = APP / "CreativeGen.h"
    path.write_text("\n".join(lines))
    print("wrote", path.relative_to(ROOT))


def write_logo(ui: dict) -> None:
    logo_name = ui.get("logo", "logo.png")
    logo_path = CREATIVE_DIR / logo_name
    if not logo_path.is_file():
        # Fallback to assets/
        alt = ROOT / "assets" / "somnium_logo.png"
        if alt.is_file():
            logo_path = alt
        else:
            print(f"skip logo: missing {logo_name}", file=sys.stderr)
            return

    try:
        from PIL import Image
    except ImportError:
        print("skip logo: pillow not installed", file=sys.stderr)
        return

    max_w = int(ui.get("logo_max_w", 160))
    max_h = int(ui.get("logo_max_h", 56))
    im = Image.open(logo_path).convert("RGBA")
    im.thumbnail((max_w, max_h), Image.Resampling.LANCZOS)
    w, h = im.size
    pixels: list[str] = []
    for y in range(h):
        for x in range(w):
            r, g, b, a = im.getpixel((x, y))
            if a < 16:
                r = g = b = 0
            pixels.append(f"0x{rgb565([r, g, b]):04X}")

    # 12 values per line
    body_lines = []
    for i in range(0, len(pixels), 12):
        body_lines.append(",".join(pixels[i : i + 12]) + ",")

    text = (
        "#pragma once\n"
        "#include <Arduino.h>\n"
        "// GENERATED by tools/sync_creative.py — do not edit by hand.\n"
        f"// Source: {logo_path.relative_to(ROOT)}\n"
        f"constexpr int16_t kLogoW = {w};\n"
        f"constexpr int16_t kLogoH = {h};\n"
        f"const uint16_t kLogoRgb565[{w * h}] PROGMEM = {{\n"
        + "\n".join(body_lines)
        + "\n};\n"
    )
    path = APP / "LogoBitmap.h"
    path.write_text(text)
    print("wrote", path.relative_to(ROOT), f"({w}x{h})")


def main() -> int:
    if not CREATIVE_JSON.is_file():
        print(f"missing {CREATIVE_JSON}", file=sys.stderr)
        return 1
    data = json.loads(CREATIVE_JSON.read_text())
    modes = data.get("modes") or []
    if not modes:
        print("creative.json has no modes", file=sys.stderr)
        return 1
    brand = data.get("brand") or {}
    if not validate_firmware_text(modes, brand):
        return 1
    write_mode_previews(modes)
    write_modes(modes)
    write_theme(data.get("theme") or {}, data.get("ui") or {}, brand)
    write_logo(data.get("ui") or {})
    print("sync ok — rebuild firmware after theme/mode/logo changes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
